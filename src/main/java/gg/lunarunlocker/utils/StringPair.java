package gg.lunarunlocker.utils;


public class StringPair {
    private final String u;
    private final String A;

    public StringPair(String string, String string2) {
        this.u = string;
        this.A = string2;
    }

    public String K() {
        return this.u;
    }

    public String H() {
        return this.A;
    }
}
